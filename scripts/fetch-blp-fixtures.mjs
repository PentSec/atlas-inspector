// fetch-blp-fixtures.mjs — pull real BLP files from wago.tools into
// tests/fixtures/blp/ so the decode pipeline and ADR-008 goldens run on real
// data (not synthetic buffers). Same upstream the server uses.
//
//   node scripts/fetch-blp-fixtures.mjs            -> default set
//   node scripts/fetch-blp-fixtures.mjs 134400     -> just that fdid
import { mkdir, rename, writeFile } from "node:fs/promises";
import path from "node:path";

const USER_AGENT = "atlas-inspector/0.2.0 (https://github.com/)";
const OUT_DIR = path.resolve(import.meta.dirname, "../tests/fixtures/blp");

// [fdid, output filename, optional pin to a wago build version]
const DEFAULT_SET = [
    [5548240, "5548240.blp", "11.0.0.54311"], // DXT5-with-alpha atlas
    [134400, "134400.blp", null], // DXT1 icon, 7 mipmaps
    [130871, "130871.blp", "6.0.1.18379"], // DXT1 plain texture
];

function buildUrl(fdid, version) {
    return `https://wago.tools/api/casc/${fdid}${
        version ? `?version=${encodeURIComponent(version)}` : ""
    }`;
}

async function fetchOne(fdid, outName, version) {
    const url = buildUrl(fdid, version);
    const res = await fetch(url, {
        headers: { "User-Agent": USER_AGENT },
        redirect: "follow",
        signal: AbortSignal.timeout(60_000),
    });
    if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length === 0) throw new Error(`empty body for ${url}`);
    const tmp = path.join(OUT_DIR, `${outName}.tmp`);
    await writeFile(tmp, buf);
    await rename(tmp, path.join(OUT_DIR, outName));
    const { createHash } = await import("node:crypto");
    const sha = createHash("sha256").update(buf).digest("hex");
    process.stdout.write(
        `✓ ${outName}  ${buf.length.toLocaleString()} bytes  sha256=${sha}  <- ${url}\n`,
    );
    return { outName, sha, url };
}

async function main() {
    await mkdir(OUT_DIR, { recursive: true });
    const args = process.argv.slice(2).filter((a) => !a.startsWith("-"));
    const set = args.length
        ? DEFAULT_SET.filter(([fdid]) => args.includes(String(fdid)))
        : DEFAULT_SET;
    if (!set.length) throw new Error(`no fixture fdids: ${args.join(", ")}`);

    const rows = [];
    for (const [fdid, outName, version] of set) {
        try {
            rows.push(await fetchOne(fdid, outName, version));
        } catch (err) {
            process.stderr.write(`✗ ${fdid}: ${err.message}\n`);
        }
    }

    // Keep the provenance README honest whenever the set changes.
    if (rows.length) {
        const lines = [
            "# BLP fixtures",
            "",
            "Real BLP files pulled from [wago.tools](https://wago.tools) (same upstream the",
            "server talks to). Generated by `npm run fetch:blp-fixtures` — edit the defaults",
            "in `scripts/fetch-blp-fixtures.mjs` and re-run to extend.",
            "",
            ...rows.map((r) => `- \`${r.outName}\` — sha256 \`${r.sha}\` — <${r.url}>`),
        ];
        await writeFile(path.join(OUT_DIR, "README.md"), lines.join("\n") + "\n");
    }
}

main().catch((err) => {
    process.stderr.write(`fetch-blp-fixtures: ${err.message}\n`);
    process.exit(2);
});
